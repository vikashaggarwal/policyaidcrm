// Joins supabase/migrations/*.sql, in order, into supabase/bundle.sql so the whole database
// can be set up by pasting one file into the Supabase SQL Editor (no command line needed).
// Run after adding a migration:  npm run db:bundle   (a test fails if the bundle is out of date)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase");
const files = readdirSync(join(root, "migrations")).filter((f) => f.endsWith(".sql")).sort();

const parts = [
  "-- Dial Desk: complete database setup (generated by scripts/bundle-sql.mjs: do not edit by hand).",
  `-- Contains ${files.length} migrations, in order: ${files.join(", ")}`,
  "-- Paste the whole file into Supabase > SQL Editor > New query > Run. Run it once on a new project.",
  "",
];
for (const f of files) {
  parts.push(`-- ============================================================ ${f}`, readFileSync(join(root, "migrations", f), "utf8").trimEnd(), "");
}
writeFileSync(join(root, "bundle.sql"), parts.join("\n"));
console.log(`Wrote supabase/bundle.sql from ${files.length} migrations`);
